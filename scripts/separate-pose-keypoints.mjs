const NAMES = ["nose", "neck", "r_shoulder", "r_elbow", "r_wrist", "l_shoulder", "l_elbow", "l_wrist", "r_hip", "r_knee", "r_ankle", "l_hip", "l_knee", "l_ankle", "r_eye", "l_eye", "r_ear", "l_ear"];

function clamp(n) {
  return Math.round(Math.min(0.94, Math.max(0.06, n)) * 10000) / 10000;
}

function skeleton(width, height, joints) {
  const nose = joints.nose;
  const neck = joints.neck;
  const dx = nose[0] - neck[0];
  const dy = nose[1] - neck[1];
  const len = Math.hypot(dx, dy) || 0.08;
  const ux = dx / len;
  const uy = dy / len;
  const px = -uy;
  const py = ux;
  const head = {
    r_eye: [nose[0] - px * 0.028 + ux * 0.008, nose[1] - py * 0.028 + uy * 0.008],
    l_eye: [nose[0] + px * 0.028 + ux * 0.008, nose[1] + py * 0.028 + uy * 0.008],
    r_ear: [nose[0] - px * 0.062 - ux * 0.012, nose[1] - py * 0.062 - uy * 0.008],
    l_ear: [nose[0] + px * 0.062 - ux * 0.012, nose[1] + py * 0.062 - uy * 0.008],
  };
  return {
    width,
    height,
    points: NAMES.map((name) => {
      const point = { ...joints, ...head }[name];
      if (!point) throw new Error(`missing ${name}`);
      return [clamp(point[0]), clamp(point[1])];
    }),
  };
}

